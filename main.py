import os
import re
import traceback
import urllib.request
import webbrowser
from urllib.parse import quote

from kivy.app import App
from kivy.clock import Clock
from kivy.uix.label import Label

ON_ANDROID = "ANDROID_ARGUMENT" in os.environ
STATE = {"error": None}  # set by any step that fails, shown on screen


def fail(prefix):
    STATE["error"] = prefix + "\n" + traceback.format_exc()


try:
    from video_downloader import PORT, start_server
except Exception:
    PORT, start_server = 8765, None
    fail("Cannot import video_downloader")

BASE_URL = "http://127.0.0.1:%d/" % PORT

ANDROID = False
if ON_ANDROID:
    try:
        # Only pyjnius is needed: the `android.runnables` helper is not shipped
        # in this build ("No module named 'android.runnables'").
        from jnius import PythonJavaClass, autoclass, java_method
        ANDROID = True
    except Exception:
        fail("Cannot import jnius")

WV = [None]  # the Android WebView once created


if ANDROID:
    _PENDING = []  # keep Python-side Java objects alive until they are no longer needed

    class UiRunnable(PythonJavaClass):
        __javainterfaces__ = ["java/lang/Runnable"]
        __javacontext__ = "app"

        def __init__(self, func):
            super().__init__()
            self.func = func

        @java_method("()V")
        def run(self):
            try:
                self.func()
            finally:
                if self in _PENDING:
                    _PENDING.remove(self)

    def activity():
        return autoclass("org.kivy.android.PythonActivity").mActivity

    def run_on_ui(func):
        r = UiRunnable(func)
        _PENDING.append(r)
        activity().runOnUiThread(r)

    # ---- links shared from other apps (Share -> this app) ----
    def read_shared_url(intent):
        try:
            if intent is None or intent.getAction() != "android.intent.action.SEND":
                return None
            text = intent.getStringExtra("android.intent.extra.TEXT") or ""
            m = re.search(r"https?://\S+", text)
            return m.group(0) if m else None
        except Exception:
            return None

    def take_shared_url():
        """URL from the launching intent; the intent is cleared so that reopening
        the app from the recents list does not start the same download again."""
        act = activity()
        url = read_shared_url(act.getIntent())
        if url:
            act.setIntent(autoclass("android.content.Intent")())
        return url

    class IntentListener(PythonJavaClass):
        __javainterfaces__ = ["org/kivy/android/PythonActivity$NewIntentListener"]
        __javacontext__ = "app"

        @java_method("(Landroid/content/Intent;)V")
        def onNewIntent(self, intent):
            # A link was shared while the app is already open.
            try:
                url = read_shared_url(intent)
                if url and WV[0] is not None:
                    WV[0].loadUrl(BASE_URL + "?u=" + quote(url, safe=""))
            except Exception:
                pass

    def register_intent_listener():
        listener = IntentListener()
        _PENDING.append(listener)
        activity().registerNewIntentListener(listener)

    # ---- background service ----
    def start_service():
        # Class name is generated by python-for-android: Service + <service name>.
        Service = autoclass("org.videodl.videodl.ServiceDownloader")
        Service.start(activity(), "")

    def request_notifications():
        # Android 13+: without this the foreground-service notification is hidden.
        try:
            perm = "android.permission.POST_NOTIFICATIONS"
            if autoclass("android.os.Build$VERSION").SDK_INT >= 33:
                act = activity()
                if act.checkSelfPermission(perm) != 0:
                    act.requestPermissions([perm], 0)
        except Exception:
            pass

    def open_webview(url):
        run_on_ui(lambda: _open_webview(url))

    def _open_webview(url):
        # Runs on the Android UI thread; errors are caught so they can be shown.
        try:
            WebView = autoclass("android.webkit.WebView")
            WebViewClient = autoclass("android.webkit.WebViewClient")
            Color = autoclass("android.graphics.Color")
            act = activity()
            wv = WebView(act)
            settings = wv.getSettings()
            settings.setJavaScriptEnabled(True)
            settings.setDomStorageEnabled(True)
            wv.setBackgroundColor(Color.parseColor("#0f172a"))
            wv.setWebViewClient(WebViewClient())
            act.setContentView(wv)
            WV[0] = wv
            wv.loadUrl(url)
        except Exception:
            fail("Cannot open WebView")


class DownloaderApp(App):
    def build(self):
        # English text on purpose: Kivy's default font has no Arabic glyphs.
        self.label = Label(text="Starting...", halign="center", valign="middle")
        self.label.bind(size=lambda w, s: setattr(w, "text_size", (s[0] - 40, s[1])))
        self.server = None  # only set when the server runs inside this process
        self.mode = "local"
        self.attempts = 0
        self.opened = False
        self.shared = None
        if STATE["error"] is None:
            if ANDROID:
                try:
                    start_service()
                    self.mode = "service"
                except Exception:
                    traceback.print_exc()  # fall back to serving inside the app
            if self.mode == "local":
                self.start_local()
        Clock.schedule_interval(self.refresh_error, 1)
        return self.label

    def start_local(self):
        try:
            self.server = start_server()
            self.mode = "local"
        except Exception:
            fail("Cannot start local server on port %d" % PORT)

    def refresh_error(self, dt):
        # Visible only while the Kivy view is on screen (i.e. WebView not shown).
        if STATE["error"]:
            self.label.text = "Error:\n" + STATE["error"][-1500:]

    def on_start(self):
        if ANDROID:
            try:
                self.shared = take_shared_url()
            except Exception:
                self.shared = None
        Clock.schedule_interval(self.wait_for_server, 0.5)

    @staticmethod
    def server_ok():
        try:
            urllib.request.urlopen(BASE_URL, timeout=1).read(1)
            return True
        except Exception:
            return False

    def wait_for_server(self, dt):
        if STATE["error"] or self.opened:
            return False
        self.attempts += 1
        if self.server_ok():
            self.opened = True
            self.open_ui()
            return False
        if self.mode == "service" and self.attempts == 16:  # ~8 s without an answer
            self.start_local()
        if self.attempts > 40:
            fail("Local server did not answer at " + BASE_URL)
            return False
        return True

    def open_ui(self):
        url = BASE_URL
        if self.shared:
            url += "?u=" + quote(self.shared, safe="")
        if ANDROID:
            try:
                open_webview(url)
                register_intent_listener()
                Clock.schedule_once(lambda dt: run_on_ui(request_notifications), 4)
            except Exception:
                fail("Cannot schedule WebView on the UI thread")
        else:
            self.label.text = "Open " + BASE_URL
            webbrowser.open(url)

    def on_pause(self):
        return True  # keep the app alive in the background

    def on_stop(self):
        if self.server is not None:
            self.server.shutdown()
            self.server.server_close()


if __name__ == "__main__":
    DownloaderApp().run()
